using System.Text;

namespace Norse.Abstractions.Contracts.Generator;

/// <summary>
/// Emits a <c>RegisterOutcomeSurrogates</c> extension registering <c>Outcome&lt;T&gt;</c> → <c>T</c>
/// passthrough surrogates for every closed response type on the contract (spec §9's "transparent
/// passthrough" wire-format mandate) — one line per distinct payload type, deduplicated, since
/// registering the same closed type twice throws at runtime. Emitted only alongside WireHost and
/// InProcessHost output — never Contract mode, which ships into service realms that must never
/// carry a protobuf-net reference (architect's ruling, 2026-07-24: gRPC/protobuf never sifts into
/// a service realm).
/// </summary>
static class OutcomeSurrogatesEmitter
{
	internal static string Emit(GatewayInterfaceModel model)
	{
		StringBuilder builder = new();
		builder.AppendLine("// <auto-generated/>");
		builder.AppendLine($"namespace {model.Namespace};");
		builder.AppendLine();
		builder.AppendLine("using Norse.Abstractions.Contracts;");
		builder.AppendLine("using ProtoBuf.Meta;");
		builder.AppendLine();
		builder.AppendLine($"static class {model.ContextName}OutcomeSurrogates");
		builder.AppendLine("{");
		builder.AppendLine("\tpublic static RuntimeTypeModel RegisterOutcomeSurrogates(this RuntimeTypeModel model)");
		builder.AppendLine("\t{");
		foreach (var responseType in model.Methods.Select(m => m.ResponseTypeName).Distinct(StringComparer.Ordinal))
			builder.AppendLine($"\t\tmodel.Add(typeof(Outcome<{responseType}>), applyDefaultBehaviour: false).SetSurrogate(typeof({responseType}));");
		builder.AppendLine("\t\treturn model;");
		builder.AppendLine("\t}");
		builder.AppendLine("}");
		return builder.ToString();
	}
}
