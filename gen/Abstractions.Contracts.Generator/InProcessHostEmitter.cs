			builder.AppendLine($"\treadonly FluentValidation.IValidator<{method.RequestTypeName}> {validatorFieldName};");
		}
		builder.AppendLine();
		builder.AppendLine($"\tpublic {model.ContextName}InProcessGateway(");
		builder.AppendLine($"\t\t{model.ServiceInterfaceName} service,");
		builder.AppendLine("\t\tMicrosoft.Extensions.Logging.ILoggerFactory loggerFactory,");
		builder.AppendLine("\t\tMicrosoft.AspNetCore.Authorization.IAuthorizationService authorizationService,");
		builder.AppendLine("\t\tMicrosoft.AspNetCore.Components.Authorization.AuthenticationStateProvider authenticationStateProvider,");
		for (var i = 0; i < model.Methods.Length; i++)
		{
			var method = model.Methods[i];
			var paramName = $"{char.ToLowerInvariant(method.Name[0])}{method.Name.Substring(1)}Validator";
			var separator = i == model.Methods.Length - 1 ? ")" : ",";
			builder.AppendLine($"\t\tFluentValidation.IValidator<{method.RequestTypeName}> {paramName}{separator}");
		}
		builder.AppendLine("\t{");
		builder.AppendLine("\t\t_service = service;");
		builder.AppendLine("\t\t_loggerFactory = loggerFactory;");
		builder.AppendLine("\t\t_authorizationService = authorizationService;");
		builder.AppendLine("\t\t_authenticationStateProvider = authenticationStateProvider;");
		foreach (var method in model.Methods)
		{
			var paramName = $"{char.ToLowerInvariant(method.Name[0])}{method.Name.Substring(1)}Validator";
			var fieldName = $"_{paramName}";
			builder.AppendLine($"\t\t{fieldName} = {paramName};");
		}
		builder.AppendLine("\t}");
		builder.AppendLine();
		builder.AppendLine("\tasync ValueTask<System.Security.Claims.ClaimsPrincipal> GetPrincipalAsync() =>");
		builder.AppendLine("\t\t(await _authenticationStateProvider.GetAuthenticationStateAsync().ConfigureAwait(false)).User;");
		builder.AppendLine();
		foreach (var (name, requestTypeName, responseType, policyName) in model.Methods)
		{
			var validatorFieldName = $"_{char.ToLowerInvariant(name[0])}{name.Substring(1)}Validator";
			// One shape throughout: void-success methods use responseType = "Unit" via the
			// IBehavior<,> family's TResponse — never a second, non-generic behavior/chain shape
			// (2026-07-24 amendment). The service already returns Outcome<TResponse> directly
			// (spec §9, 2026-07-24 amendment) — the innermost call awaits and returns it unchanged,
			// no Ok-wrapping ceremony; that was only needed when the service returned a bare payload.
			var innermostSuccessExpression = $"await _service.{name}(request).ConfigureAwait(false)";

			builder.AppendLine($"\tpublic async ValueTask<Outcome<{responseType}>> {name}({requestTypeName} request, CancellationToken cancellationToken = default)");
			builder.AppendLine("\t{");
			builder.AppendLine($"\t\tvar telemetry = new Norse.Infrastructure.Web.Server.Mediator.TelemetryBehavior<{requestTypeName}, {responseType}>(_loggerFactory.CreateLogger<Norse.Infrastructure.Web.Server.Mediator.TelemetryBehavior<{requestTypeName}, {responseType}>>());");
			builder.AppendLine($"\t\tvar exceptionTranslation = new Norse.Infrastructure.Web.Server.Mediator.ExceptionTranslationBehavior<{requestTypeName}, {responseType}>(_loggerFactory.CreateLogger<Norse.Infrastructure.Web.Server.Mediator.ExceptionTranslationBehavior<{requestTypeName}, {responseType}>>());");
			builder.AppendLine($"\t\tvar authorization = new Norse.Infrastructure.Web.Server.Mediator.AuthorizationBehavior<{requestTypeName}, {responseType}>(\"{policyName}\", _authorizationService, GetPrincipalAsync);");
