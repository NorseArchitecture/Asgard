	internal static string Emit(GatewayInterfaceModel model)
	{
		var builder = new StringBuilder();
		builder.AppendLine("// <auto-generated/>");
		builder.AppendLine($"namespace {model.Namespace};");
		builder.AppendLine();
		builder.AppendLine("using Norse.Abstractions.Contracts;");
		builder.AppendLine("using Norse.Abstractions.Web.Server.Mediator;");
		builder.AppendLine();
		builder.AppendLine($"sealed class {model.ContextName}InProcessGateway : I{model.ContextName}Gateway");
		builder.AppendLine("{");
		builder.AppendLine($"\treadonly {model.ServiceInterfaceName} _service;");
		builder.AppendLine("\treadonly Microsoft.Extensions.Logging.ILoggerFactory _loggerFactory;");
		builder.AppendLine("\treadonly Microsoft.AspNetCore.Authorization.IAuthorizationService _authorizationService;");
		builder.AppendLine("\treadonly Microsoft.AspNetCore.Components.Authorization.AuthenticationStateProvider _authenticationStateProvider;");
		foreach (var method in model.Methods)
		{
